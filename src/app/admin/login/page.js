import Wordmark from "../../../components/Wordmark";
import { siteTitle } from "../../../lib/site-branding";
import { adminTranslator, adminLanguage } from "../../../lib/admin-language";
import { currentAdmin } from "../../../lib/admin-session";
import { redirect } from "next/navigation";
import LoginForm from "./LoginForm";
export const dynamic = "force-dynamic";
export async function generateMetadata() {
  const t = await adminTranslator();
  return {
    title: `${t("Staff sign-in")} | ${siteTitle(await adminLanguage())}`,
    robots: {
      index: false,
      follow: false,
    },
    referrer: "no-referrer",
  };
}
export default async function Login() {
  const t = await adminTranslator();
  if (await currentAdmin()) redirect("/admin");
  return (
    <div className="mx-auto w-full max-w-md px-5 py-14">
      <a href="/" className="rounded-sm" aria-label="kosova.report">
        <Wordmark className="text-2xl" />
      </a>
      <section className="mt-8 rounded-lg bg-card p-6 shadow-lift">
        <h1 className="text-3xl font-extrabold tracking-[-0.025em] text-ink">
          {t("Staff sign-in")}
        </h1>
        <p className="mt-2 text-sm text-pencil">
          {" "}
          {t("Administrators and assigned report checkers.")}{" "}
        </p>
        <LoginForm />
        <p className="mt-5 text-xs text-pencil">
          {" "}
          {t(
            "For first access, use the one-time password generated by the server setup command. You will be asked to replace it immediately.",
          )}{" "}
        </p>
      </section>
    </div>
  );
}
